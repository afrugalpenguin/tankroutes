"""Generate Data/Maps.lua from OneForAll's Data/DungeonMaps.lua.

Only dungeons whose layouts come from Forever Simple World Map 0.30.2 (MIT) are kept.
Usage: python -I tools/convert_ofa_maps.py <OneForAll DungeonMaps.lua> Data/Maps.lua
"""
import os
import re
import sys

# Layouts from Forever Simple World Map 0.30.2 (MIT). Anything else is restricted.
MIT_IDS = [33, 34, 36, 43, 47, 70, 90, 109, 129, 189, 209, 229, 230, 249, 289,
           329, 349, 389, 429, 2959, 2998, 2999, 3065]
RESTRICTED_IDS = {48, 2970, 2974, 2994, 3001, 3039}

ENTRY_RE = re.compile(r"^\s*\[(\d+)\]\s*=\s*\{\s*--\s*(.+?)\s*$")
TILES_RE = re.compile(r"^\s*tiles\s*=\s*\{(.*)\},?\s*$")
NUM = r"(-?\d+(?:\.\d+)?)"
# fileID, u, v, width, height, angle and an optional sublevel (missing means 0).
TILE_RE = re.compile(r"\{(\d+)," + ",".join([NUM] * 5) + r"(?:," + NUM + r")?\}")
STRING_TILE_RE = re.compile(r'\{"[^"]*"')
VERSION_RE = re.compile(r"^##\s*Version:\s*(\S+)\s*$")

HEADER = """\
-- Generated by tools/convert_ofa_maps.py. Do not edit by hand.
-- Room layouts from Forever Simple World Map 0.30.2 by Tarolg (MIT), via OneForAll {version} by
-- Smoergi (GPL-3.0-or-later). See THIRD_PARTY_LICENSES.txt. The room images are the game
-- client's own minimap textures. Coordinates are world yards (u east, v south).
-- Maps[instanceID] = {{ name, rooms = {{ {{ fileID, u, v, width, height, angle, sublevel }} }} }}
local _, TR = ...
TR = TR or TankRoutes

TR.Maps = {{
"""


def read_version(src):
    addon_dir = os.path.dirname(os.path.dirname(os.path.abspath(src)))
    toc = os.path.join(addon_dir, "OneForAll.toc")
    if not os.path.isfile(toc):
        sys.exit(f"ERROR: {toc} not found")
    with open(toc, encoding="utf-8-sig") as f:
        for line in f:
            m = VERSION_RE.match(line)
            if m:
                return m.group(1)
    sys.exit(f"ERROR: no ## Version: line in {toc}")


def parse(path):
    maps = {}
    current = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = ENTRY_RE.match(line)
            if m:
                current = (int(m.group(1)), re.sub(r"\s*\(.*\)$", "", m.group(2)))
                continue
            t = TILES_RE.match(line)
            if t and current:
                body = t.group(1)
                rooms = [r[:6] + (r[6] or "0",) for r in TILE_RE.findall(body)]
                skipped = len(STRING_TILE_RE.findall(body))
                total = body.count("{")
                maps[current[0]] = (current[1], rooms, skipped, total)
                current = None
    return maps


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, dst):
    version = read_version(src)
    maps = parse(src)
    out = [HEADER.format(version=version)]
    for map_id in MIT_IDS:
        if map_id in RESTRICTED_IDS:
            sys.exit(f"ERROR: {map_id} is restricted")
        if map_id not in maps:
            sys.exit(f"ERROR: no tiles found for {map_id}")
        name, rooms, skipped, total = maps[map_id]
        if not rooms:
            sys.exit(f"ERROR: {map_id} {name} has no fileID rooms")
        if len(rooms) + skipped != total:
            sys.exit(f"ERROR: {map_id} {name}: {total} tiles but only {len(rooms)} rooms "
                     f"and {skipped} addon images parsed")
        out.append(f"    [{map_id}] = {{ name = {lua_string(name)}, rooms = {{\n")
        for r in rooms:
            out.append("        {" + ",".join(r) + "},\n")
        out.append("    } },\n")
        note = f", skipped {skipped} addon images" if skipped else ""
        print(f"{map_id:5d} {name}: {len(rooms)} rooms{note}")
    out.append("}\n")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print(f"OneForAll version {version}")
    print(f"Wrote {len(MIT_IDS)} maps to {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
